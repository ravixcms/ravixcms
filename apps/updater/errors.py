class UpdateError(Exception):
    """خطای قابل‌فهم برای مدیر. پیام باید امن باشد (بدون کلید/رمز/مسیرهای حساس)؛ پیش از ذخیره دوباره پاک‌سازی هم می‌شود."""


class UpdateBusy(UpdateError):
    """ارتقای دیگری در جریان است."""


class UpdateBlocked(UpdateError):
    """ناسازگاری/پیش‌شرط‌های برآورده‌نشده؛ پیش از هر تغییری متوقف شد."""
