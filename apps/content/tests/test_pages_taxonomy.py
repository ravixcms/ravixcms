from django.test import TestCase
from django.urls import reverse

from apps.accounts.permissions import Role
from apps.accounts.tests.test_auth import make_user
from apps.audit.models import AuditLog
from apps.content.models import Category, Page, Post, PublishStatus, Tag


def page_data(**kw):
    data = {"title": "درباره ما", "slug": "", "body": "ما یک تیم هستیم.", "status": "draft", "seo_title": "", "seo_description": ""}
    data.update(kw)
    return data


class PageTests(TestCase):
    def setUp(self):
        self.admin = make_user("adm", Role.ADMIN)
        self.author = make_user("aut", Role.AUTHOR)
        self.client.force_login(self.admin)

    def test_create_about_and_contact_pages(self):
        for title, slug in (("درباره ما", "about"), ("تماس با ما", "contact")):
            r = self.client.post(reverse("content:page_create"), page_data(title=title, slug=slug, status="published"), follow=True)
            self.assertContains(r, "با موفقیت ایجاد شد")
        self.assertEqual(set(Page.objects.values_list("slug", flat=True)), {"about", "contact"})
        about = Page.objects.get(slug="about")
        self.assertEqual(about.author, self.admin)
        self.assertTrue(about.is_live)
        self.assertEqual(AuditLog.objects.filter(action="create", object_type="صفحه").count(), 2)

    def test_slug_autogenerated_from_persian_title(self):
        self.client.post(reverse("content:page_create"), page_data())
        self.assertEqual(Page.objects.get().slug, "درباره-ما")

    def test_duplicate_slug_rejected(self):
        Page.objects.create(title="الف", slug="about", body="x")
        r = self.client.post(reverse("content:page_create"), page_data(slug="about"))
        self.assertTrue(r.context["form"].errors.get("slug"))

    def test_seo_fields_saved_and_length_validated(self):
        self.client.post(reverse("content:page_create"), page_data(seo_title="عنوان سئو", seo_description="توضیح کوتاه سئو"))
        page = Page.objects.get()
        self.assertEqual((page.seo_title, page.seo_description), ("عنوان سئو", "توضیح کوتاه سئو"))
        self.assertEqual(page.effective_title_tag, "عنوان سئو")
        r = self.client.post(reverse("content:page_create"), page_data(title="دیگر", seo_title="الف" * 71, seo_description="ب" * 161))
        self.assertTrue(r.context["form"].errors.get("seo_title"))
        self.assertTrue(r.context["form"].errors.get("seo_description"))

    def test_title_tag_falls_back_to_title(self):
        self.client.post(reverse("content:page_create"), page_data())
        self.assertEqual(Page.objects.get().effective_title_tag, "درباره ما")

    def test_draft_and_publish_cycle_with_scheduled_not_allowed(self):
        page = Page.objects.create(title="پ", body="x")
        self.assertEqual(page.status, PublishStatus.DRAFT)
        self.client.post(reverse("content:page_update", args=[page.pk]), page_data(title="پ", slug=page.slug, status="published"))
        page.refresh_from_db()
        self.assertTrue(page.is_live)
        r = self.client.post(reverse("content:page_update", args=[page.pk]), page_data(title="پ", slug=page.slug, status="scheduled"))
        self.assertTrue(r.context["form"].errors.get("status"))  # صفحات زمان‌بندی ندارند

    def test_edit_keeps_author_and_updates_html_and_audit(self):
        page = Page.objects.create(title="پ", body="x", author=self.author)
        self.client.post(reverse("content:page_update", args=[page.pk]), page_data(title="جدید", slug=page.slug, body="**تیره**"))
        page.refresh_from_db()
        self.assertEqual(page.author, self.author)
        self.assertIn("<strong>تیره</strong>", page.body_html)
        self.assertTrue(AuditLog.objects.filter(action="update", object_type="صفحه").exists())

    def test_delete_page(self):
        page = Page.objects.create(title="حذف", body="x")
        self.client.post(reverse("content:page_delete", args=[page.pk]))
        self.assertFalse(Page.objects.exists())
        self.assertTrue(AuditLog.objects.filter(action="delete", object_type="صفحه").exists())

    def test_list_search_filter_pagination(self):
        for i in range(17):
            Page.objects.create(title=f"صفحه {i}", body="متن", status="published" if i % 2 else "draft")
        Page.objects.create(title="ویژه", body="کلمه‌یکتا")
        url = reverse("content:page_list")
        self.assertEqual(len(self.client.get(url).context["pages"]), 15)
        self.assertEqual(len(self.client.get(url, {"page": 2}).context["pages"]), 3)
        self.assertEqual([p.title for p in self.client.get(url, {"q": "کلمه‌یکتا"}).context["pages"]], ["ویژه"])
        self.assertTrue(all(p.status == "published" for p in self.client.get(url, {"status": "published"}).context["pages"]))

    def test_non_admins_blocked(self):
        page = Page.objects.create(title="پ", body="x")
        for role_user in (self.author, make_user("usr", Role.USER)):
            self.client.force_login(role_user)
            for name, args in (("page_list", []), ("page_create", []), ("page_detail", [page.pk]),
                               ("page_update", [page.pk]), ("page_delete", [page.pk])):
                self.assertEqual(self.client.get(reverse(f"content:{name}", args=args)).status_code, 403, (role_user.role, name))
            self.assertEqual(self.client.post(reverse("content:page_delete", args=[page.pk])).status_code, 403)
        self.assertTrue(Page.objects.filter(pk=page.pk).exists())

    def test_page_detail_sanitized(self):
        page = Page.objects.create(title="پ", body="<script>alert(1)</script> [x](javascript:alert(1))")
        r = self.client.get(reverse("content:page_detail", args=[page.pk]))
        self.assertNotContains(r, "<script>alert")
        self.assertNotContains(r, "javascript:")


class TaxonomyTests(TestCase):
    def setUp(self):
        self.admin = make_user("adm", Role.ADMIN)
        self.author = make_user("aut", Role.AUTHOR)
        self.client.force_login(self.admin)

    def test_category_crud_with_auto_slug(self):
        r = self.client.post(reverse("content:category_create"), {"name": "اخبار فناوری", "slug": "", "description": "توضیح", "parent": ""}, follow=True)
        self.assertContains(r, "با موفقیت ایجاد شد")
        cat = Category.objects.get()
        self.assertEqual(cat.slug, "اخبار-فناوری")
        self.client.post(reverse("content:category_update", args=[cat.pk]), {"name": "اخبار", "slug": cat.slug, "description": "", "parent": ""})
        cat.refresh_from_db()
        self.assertEqual(cat.name, "اخبار")
        self.client.post(reverse("content:category_delete", args=[cat.pk]))
        self.assertFalse(Category.objects.exists())
        actions = set(AuditLog.objects.filter(object_type="دسته‌بندی").values_list("action", flat=True))
        self.assertEqual(actions, {"create", "update", "delete"})

    def test_category_name_unique_and_blank_rejected(self):
        Category.objects.create(name="الف")
        r = self.client.post(reverse("content:category_create"), {"name": "الف", "slug": "", "description": "", "parent": ""})
        self.assertTrue(r.context["form"].errors.get("name"))
        r = self.client.post(reverse("content:category_create"), {"name": "   ", "slug": "", "description": "", "parent": ""})
        self.assertTrue(r.context["form"].errors.get("name"))

    def test_hierarchy_and_cycle_prevention(self):
        root = Category.objects.create(name="ریشه")
        child = Category.objects.create(name="فرزند", parent=root)
        grand = Category.objects.create(name="نوه", parent=child)
        self.assertEqual(root.descendant_ids(), {child.pk, grand.pk})
        # قرار دادن «ریشه» زیر «نوه» حلقه می‌سازد و باید رد شود
        r = self.client.post(reverse("content:category_update", args=[root.pk]),
                             {"name": "ریشه", "slug": root.slug, "description": "", "parent": grand.pk})
        self.assertTrue(r.context["form"].errors.get("parent"))
        r = self.client.post(reverse("content:category_update", args=[root.pk]),
                             {"name": "ریشه", "slug": root.slug, "description": "", "parent": root.pk})
        self.assertTrue(r.context["form"].errors.get("parent"))
        root.refresh_from_db()
        self.assertIsNone(root.parent)

    def test_deleting_category_keeps_posts_and_children(self):
        parent = Category.objects.create(name="والد")
        child = Category.objects.create(name="فرزند", parent=parent)
        post = Post.objects.create(title="پ", body="x", author=self.author)
        post.categories.add(parent)
        self.client.post(reverse("content:category_delete", args=[parent.pk]))
        child.refresh_from_db()
        self.assertIsNone(child.parent)
        self.assertTrue(Post.objects.filter(pk=post.pk).exists())
        self.assertEqual(post.categories.count(), 0)

    def test_category_list_shows_post_counts(self):
        cat = Category.objects.create(name="شمارش")
        for i in range(3):
            Post.objects.create(title=f"p{i}", body="x").categories.add(cat)
        self.assertEqual(self.client.get(reverse("content:category_list")).context["categories"][0].post_count, 3)

    def test_tag_crud_search_unique(self):
        self.client.post(reverse("content:tag_create"), {"name": "پایتون", "slug": ""})
        tag = Tag.objects.get()
        self.assertEqual(tag.slug, "پایتون")
        r = self.client.post(reverse("content:tag_create"), {"name": "پایتون", "slug": ""})
        self.assertTrue(r.context["form"].errors.get("name"))
        Tag.objects.create(name="جنگو")
        self.assertEqual([t.name for t in self.client.get(reverse("content:tag_list"), {"q": "جنگ"}).context["tags"]], ["جنگو"])
        self.client.post(reverse("content:tag_update", args=[tag.pk]), {"name": "پایتون ۳", "slug": tag.slug})
        tag.refresh_from_db()
        self.assertEqual(tag.name, "پایتون ۳")
        self.client.post(reverse("content:tag_delete", args=[tag.pk]))
        self.assertFalse(Tag.objects.filter(pk=tag.pk).exists())

    def test_slug_collision_gets_suffix(self):
        Tag.objects.create(name="الف ب")
        t2 = Tag.objects.create(name="الف-ب")  # نام متفاوت، نامک یکسان
        self.assertEqual(t2.slug, "الف-ب-2")

    def test_author_and_user_cannot_manage_taxonomy(self):
        cat, tag = Category.objects.create(name="ک"), Tag.objects.create(name="ت")
        for user in (self.author, make_user("usr", Role.USER)):
            self.client.force_login(user)
            for name in ("category_list", "category_create", "tag_list", "tag_create"):
                self.assertEqual(self.client.get(reverse(f"content:{name}")).status_code, 403, name)
            self.assertEqual(self.client.post(reverse("content:category_delete", args=[cat.pk])).status_code, 403)
            self.assertEqual(self.client.post(reverse("content:tag_delete", args=[tag.pk])).status_code, 403)
        self.assertTrue(Category.objects.exists() and Tag.objects.exists())

    def test_author_can_still_assign_existing_taxonomy_to_own_post(self):
        cat = Category.objects.create(name="ک")
        self.client.force_login(self.author)
        self.client.post(reverse("content:post_create"), {"title": "ت", "body": "ب", "status": "draft", "categories": [cat.pk]})
        self.assertEqual(list(Post.objects.get().categories.all()), [cat])


class SidebarTests(TestCase):
    def test_navigation_per_role(self):
        expect = {
            Role.USER: set(),
            Role.AUTHOR: {"content:post_list", "media_library:media_list"},
            Role.ADMIN: {"content:post_list", "content:page_list", "content:category_list", "content:tag_list",
                         "media_library:media_list", "audit:log_list"},
        }
        every = {"content:post_list", "content:page_list", "content:category_list", "content:tag_list",
                 "media_library:media_list", "audit:log_list"}
        for role, allowed in expect.items():
            self.client.force_login(make_user(role.value, role))
            html = self.client.get(reverse("dashboard:home")).content.decode()
            for name in every:
                url = f'href="{reverse(name)}"'
                self.assertEqual(url in html, name in allowed, (role, name))
