class PostImageTests(PostBase):
    def setUp(self):
        super().setUp()
        self.login(self.admin)

    def image(self, name="cover.png", content=None):
        return SimpleUploadedFile(name, content or png_bytes(), content_type="image/png")

    def test_featured_image_upload_replace_and_delete(self):
        self.client.post(self.create_url, post_data(author=self.admin.pk, featured_image=self.image()))
        post = Post.objects.get()
        first = post.featured_image.path
        self.assertTrue(os.path.exists(first))
        self.client.post(reverse("content:post_update", args=[post.pk]),
                         post_data(author=self.admin.pk, featured_image=self.image("second.png", png_bytes((30, 30), "green"))))
        post.refresh_from_db()
        self.assertFalse(os.path.exists(first))  # فایل قبلی پاک شد
        second = post.featured_image.path
        self.assertTrue(os.path.exists(second))
        self.client.post(reverse("content:post_delete", args=[post.pk]))
        self.assertFalse(os.path.exists(second))

    def test_clear_featured_image(self):
        self.client.post(self.create_url, post_data(author=self.admin.pk, featured_image=self.image()))
        post = Post.objects.get()
        path = post.featured_image.path
        self.client.post(reverse("content:post_update", args=[post.pk]),
                         post_data(author=self.admin.pk, **{"featured_image-clear": "on"}))
        post.refresh_from_db()
        self.assertFalse(post.featured_image)
        self.assertFalse(os.path.exists(path))

    def test_fake_image_rejected(self):
        r = self.client.post(self.create_url, post_data(author=self.admin.pk,
                             featured_image=self.image("x.png", b"<?php system($_GET['c']); ?>")))
        self.assertTrue(r.context["form"].errors.get("featured_image"))
        self.assertEqual(Post.objects.count(), 0)


class PostXSSTests(PostBase):
    def test_malicious_markdown_is_sanitized_everywhere(self):
        body = ('<script>alert("x")</script>\n\n[click](javascript:alert(1))\n\n'
                '<img src="https://e.com/a.png" onerror="alert(2)">\n\n<iframe src="https://evil"></iframe>')
        self.login(self.admin)
        self.client.post(self.create_url, post_data(title="<b>تیتر</b>", body=body, author=self.admin.pk, status="published"))
        post = Post.objects.get()
        for bad in ("<script", "javascript:", "onerror", "<iframe"):
            self.assertNotIn(bad, post.body_html)
        r = self.client.get(reverse("content:post_detail", args=[post.pk]))
        for bad in ("<script>alert", "javascript:", "onerror", "<iframe"):
            self.assertNotContains(r, bad)
        self.assertNotContains(r, "<b>تیتر</b>")  # عنوان escape می‌شود

    def test_markdown_preview_endpoint(self):
        url = reverse("content:markdown_preview")
        self.assertEqual(self.client.post(url, {"text": "x"}).status_code, 302)
        self.login(self.user)
        self.assertEqual(self.client.post(url, {"text": "x"}).status_code, 403)
        self.login(self.author)
        data = self.client.post(url, {"text": "**a** <script>alert(1)</script>"}).json()
        self.assertIn("<strong>a</strong>", data["html"])
        self.assertNotIn("<script", data["html"])
        self.assertEqual(self.client.get(url).status_code, 405)
        self.assertEqual(self.client.post(url, {"text": "a" * 200_001}).status_code, 413)
