def dt(delta_hours=0):
    return (timezone.localtime() + timedelta(hours=delta_hours)).strftime("%Y-%m-%dT%H:%M")


def post_data(**kw):
    data = {"title": "عنوان آزمایشی", "slug": "", "excerpt": "خلاصه", "body": "متن **نوشته**", "status": "draft"}
    data.update(kw)
    return data


class PostBase(MediaTestCase):
    def setUp(self):
        self.sa = make_user("sa", Role.SUPER_ADMIN)
        self.admin = make_user("adm", Role.ADMIN)
        self.author = make_user("aut", Role.AUTHOR)
        self.author2 = make_user("aut2", Role.AUTHOR)
        self.user = make_user("usr", Role.USER)
        self.create_url = reverse("content:post_create")
        self.list_url = reverse("content:post_list")

    def login(self, user):
        self.client.force_login(user)

    def make_post(self, author=None, **kw):
        defaults = dict(title="نوشته", body="متن", status=PublishStatus.DRAFT, author=author or self.author)
        defaults.update(kw)
        return Post.objects.create(**defaults)


