#!/usr/bin/env python3
"""Writes requirements.hashes.lock from requirements.lock: every pinned package with the SHA-256 of every file PyPI publishes for that exact
version (wheels and the source archive). ``pip install --require-hashes -r requirements.hashes.lock`` then accepts only those files.

Run it on the publisher's machine before building a release (it needs the network, nothing else):
    python scripts/make_hash_lock.py            # rewrites requirements.hashes.lock next to requirements.lock
    python scripts/make_hash_lock.py --check    # exits 1 when the file is not what the command would write (no network needed for a quick look at the pins)
Only the standard library is used, so it also runs where Django is not installed.
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.+!_-]+)\s*(?:#.*)?$")
HEADER = ("# Generated by scripts/make_hash_lock.py from requirements.lock — do not edit by hand.\n"
          "# pip install --require-hashes -r requirements.hashes.lock   (every file must match one of the SHA-256 values)\n")


def pins(text: str) -> list[tuple[str, str]]:
    out = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = PIN.match(line)
        if not m:
            raise SystemExit(f"requirements.lock: line is not an exact pin (name==version): {line!r}")
        out.append((m.group(1), m.group(2)))
    return out


def fetch_hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:  # noqa: S310 - fixed https host
        data = json.load(r)
    hashes = sorted({f["digests"]["sha256"] for f in data.get("urls", []) if f.get("digests", {}).get("sha256")})
    if not hashes:
        raise SystemExit(f"PyPI lists no files for {name}=={version}")
    return hashes


def render(items: list[tuple[str, str, list[str]]]) -> str:
    out = [HEADER]
    for name, version, hashes in items:
        out.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lock", default=str(ROOT / "requirements.lock"))
    ap.add_argument("--out", default=str(ROOT / "requirements.hashes.lock"))
    ap.add_argument("--check", action="store_true", help="only compare with the existing file")
    args = ap.parse_args()
    wanted = pins(Path(args.lock).read_text(encoding="utf-8"))
    text = render([(n, v, fetch_hashes(n, v)) for n, v in wanted])
    out = Path(args.out)
    if args.check:
        same = out.is_file() and out.read_text(encoding="utf-8") == text
        print("up to date" if same else "requirements.hashes.lock is out of date")
        return 0 if same else 1
    out.write_text(text, encoding="utf-8")
    print(f"{out}: {len(wanted)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
